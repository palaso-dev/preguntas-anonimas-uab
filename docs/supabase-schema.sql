create table if not exists public.confessions (
  id bigint generated by default as identity primary key,
  message text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'read', 'rejected')),
  is_featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text not null
);

insert into public.settings (key, value) values
  ('event_title', 'Confesiones Anónimas'),
  ('event_subtitle', ''),
  ('submissions_open', 'true'),
  ('live_mode', 'qr'),
  ('public_url', '')
on conflict (key) do nothing;

alter table public.confessions enable row level security;
alter table public.settings enable row level security;

drop policy if exists "Public can insert pending confessions" on public.confessions;
create policy "Public can insert pending confessions"
  on public.confessions
  for insert
  to anon, authenticated
  with check (
    status = 'pending'
    and is_featured = false
    and char_length(trim(message)) >= 5
    and char_length(trim(message)) <= 320
  );

drop policy if exists "Public can read approved confessions" on public.confessions;
create policy "Public can read approved confessions"
  on public.confessions
  for select
  to anon
  using (status in ('approved', 'read'));

drop policy if exists "Admins full access confessions" on public.confessions;
create policy "Admins full access confessions"
  on public.confessions
  for all
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Anyone can read settings" on public.settings;
create policy "Anyone can read settings"
  on public.settings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can manage settings" on public.settings;
create policy "Admins can manage settings"
  on public.settings
  for all
  to authenticated
  using (true)
  with check (true);

alter publication supabase_realtime add table public.confessions;
alter publication supabase_realtime add table public.settings;

grant usage on schema public to anon, authenticated;
grant select on public.settings to anon, authenticated;
grant insert, update, delete on public.settings to authenticated;
grant insert, select on public.confessions to anon;
grant all on public.confessions to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
